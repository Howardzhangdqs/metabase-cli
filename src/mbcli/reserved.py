_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_NEAR_CLAUSE = re.compile(r"\bnear\s+'([^']*)'", re.IGNORECASE)
_SINGLE_QUOTED = re.compile(r"'([^']*)'")


def is_reserved(word: str) -> bool:
    """Case-insensitive reserved-word membership test."""
    return word.strip("`").lower() in MYSQL_RESERVED_WORDS


def find_reserved_token(message: str) -> str | None:
    """Best-effort: the reserved word the server error is pointing at.

    Two extractions, most-specific first:
    1. MySQL syntax errors embed the offending region: ``near 'order int'`` —
       scan that fragment's identifier chunks for a reserved word.
    2. Other driver errors quote bare identifiers: ``Unknown column 'year_month'
       in 'field list'`` — single-quoted segments that are plain identifiers
       (or dotted identifier pairs, e.g. ``'db.order'``) are candidates;
       prose segments like ``'field list'`` / ``'where clause'`` contain spaces
       and are skipped, as are non-reserved words (``Table 'x.y' doesn't
       exist`` yields no hint).
    """
    near = _NEAR_CLAUSE.search(message)
    if near:
        for token in _IDENTIFIER.findall(near.group(1)):
            if token.lower() in MYSQL_RESERVED_WORDS:
                return token.lower()
    for segment in _SINGLE_QUOTED.findall(message):
        for part in segment.split("."):
            if _IDENTIFIER.fullmatch(part) and part.lower() in MYSQL_RESERVED_WORDS:
                return part.lower()
    return None
